import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const WORKS = path.join(ROOT, "public", "works");
const BRANDS = path.join(ROOT, "public", "brands");
const OUT = path.join(ROOT, "src", "content", "localMedia.js");

// folder name (lowercase) -> [category label on the site, files you expect]
// The order here is the order of the filter buttons.
const MAP = [
  ["cgi", "CGI", 6],
  ["3d", "3D", 9],
  ["telecom", "Telecom Egypt", 23],
  ["familia", "FAMILIA & PAPIA", 6],
  ["other", "OTHER", 65],
  ["video editing", "Video Editing", 34],
  ["oxi", "OXI", 5],
  ["bigcolavolt", "BIG COLA & VOLT", 12],
];

const VIDEO = /\.(mp4|webm|mov|m4v)$/i;
const IMG = /\.(webp|jpe?g|png|avif)$/i;
const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true });
const base = (f) => f.replace(/\.[^.]+$/, "");
const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const urlOf = (...p) => "/" + p.map(encodeURIComponent).join("/");
const warn = (m) => console.warn("⚠ " + m);

const dirs = fs.existsSync(WORKS)
  ? fs
      .readdirSync(WORKS, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
  : [];
if (!dirs.length) warn(`No folders found in ${WORKS}`);

const categories = [];
const items = [];
const only = process.argv.slice(2).map((s) => s.toLowerCase());
for (const [key, label, expected] of MAP.filter(
  ([k]) => !only.length || only.includes(k),
)) {
  const dir = dirs.find((d) => d.toLowerCase() === key);
  if (!dir) {
    warn(`Folder "${key}" not found in public/works`);
    continue;
  }
  const files = fs.readdirSync(path.join(WORKS, dir));
  const videos = files.filter((f) => VIDEO.test(f)).sort(natural);
  const covers = new Map(
    files.filter((f) => IMG.test(f)).map((f) => [base(f), f]),
  );
  categories.push(label);
  let missing = 0;
  for (const v of videos) {
    const cover = covers.get(base(v));
    if (!cover) missing++;
    items.push({
      id: `w-${slug(dir)}-${slug(base(v))}`,
      visible: true,
      kind: "video",
      category: label,
      title: "",
      media: { provider: "local", url: urlOf("works", dir, v) },
      poster: cover
        ? { provider: "local", url: urlOf("works", dir, cover) }
        : null,
    });
  }
  console.log(
    `${label.padEnd(18)} ${String(videos.length).padStart(3)} videos` +
      (videos.length !== expected ? `  (expected ${expected})` : "") +
      (missing ? `  — ${missing} without cover` : ""),
  );
  if (videos.length !== expected)
    warn(`${dir}: found ${videos.length}, expected ${expected}`);
}
for (const d of dirs)
  if (!MAP.some(([k]) => k === d.toLowerCase()))
    warn(`Folder "${d}" is not in MAP, skipped`);

const brands = fs.existsSync(BRANDS)
  ? fs
      .readdirSync(BRANDS)
      .filter((f) => IMG.test(f))
      .sort(natural)
      .map((f) => ({
        id: `b-${slug(base(f))}`,
        name: base(f).replace(/[-_]+/g, " "),
        logo: { provider: "local", url: urlOf("brands", f) },
      }))
  : [];
console.log(
  `Brands             ${String(brands.length).padStart(3)} logos` +
    (brands.length !== 9 ? "  (expected 9)" : ""),
);

const body =
  "// AUTO-GENERATED by scripts/gen-local-media.mjs. Do not edit by hand.\n" +
  `export const localWorks = {\n  categories: ${JSON.stringify(categories)},\n  items: [\n${items.map((i) => "    " + JSON.stringify(i)).join(",\n")}\n  ],\n};\n\n` +
  `export const localBrands = [\n${brands.map((b) => "  " + JSON.stringify(b)).join(",\n")}\n];\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(
  `\nWrote ${path.relative(ROOT, OUT)}  (${items.length} works, ${brands.length} brands)`,
);
